def canonical_mixamo_name(name: str) -> str:
    """Maps Mixamo, CC_Base_*, or Bip001-* bone names -> canonical Mixamo bone name."""
    s = name.split(":")[-1]
    s = re.sub(r"(?:_\d+)+$", "", s)
    return BONE_ALIASES.get(s.lower(), s)


def import_any_mesh(filepath: str):
    ext = os.path.splitext(filepath)[1].lower()
    before = set(bpy.data.objects)
    if ext in (".glb", ".gltf"):
        bpy.ops.import_scene.gltf(filepath=filepath)
    elif ext == ".obj":
        bpy.ops.wm.obj_import(filepath=filepath)
    elif ext == ".fbx":
        bpy.ops.import_scene.fbx(filepath=filepath)
    else:
        raise RuntimeError(f"Unsupported mesh format: {ext}")
    return [o for o in bpy.data.objects if o not in before]


def prepare_studio_character(input_path: str, target_height: float, front_yaw: str, max_faces: int):
    imported = import_any_mesh(input_path)
    meshes = [o for o in imported if o.type == "MESH" and len(o.data.vertices) > 0]
    if not meshes:
        raise RuntimeError(f"No valid mesh objects found in {input_path}")

    # Discard any tiny helper meshes only if huge real character meshes also exist
    max_v = max(len(m.data.vertices) for m in meshes)
    if max_v > 500:
        keep = []
        for m in meshes:
            nl = m.name.lower()
            if len(m.data.vertices) < 50 and any(k in nl for k in ("icosphere", "floor", "plane", "ground", "camera")):
                continue
            keep.append(m)
        if keep:
            meshes = keep

    # Bake world transforms cleanly before joining
    for o in imported:
        o.select_set(False)
    for m in meshes:
        mw = m.matrix_world.copy()
        m.parent = None
        m.matrix_world = mw
        # Clear any pre-existing skin modifiers/vertex groups so fresh rigging succeeds
        for mod in list(m.modifiers):
            if mod.type == "ARMATURE":
                m.modifiers.remove(mod)
        m.vertex_groups.clear()

    # Delete non-target objects (cameras, lights, empties, armatures) cleanly
    mesh_set = set(meshes)
    for o in list(bpy.data.objects):
        if o not in mesh_set:
            bpy.data.objects.remove(o, do_unlink=True)

    bpy.ops.object.select_all(action="DESELECT")
    for m in meshes:
        m.select_set(True)
    bpy.context.view_layer.objects.active = meshes[0]
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    if len(meshes) > 1:
        bpy.ops.object.join()

    char_obj = bpy.context.view_layer.objects.active
    char_obj.name = "AvatarMesh"
    char_obj.data.name = "AvatarMeshData"

    # Purge degenerate zero-area faces / loose floating vertices (common in Marching-Cubes outputs)
    bm_clean = bmesh.new()
    bm_clean.from_mesh(char_obj.data)
    deg_faces = [f for f in bm_clean.faces if f.calc_area() < 1e-10]
    if deg_faces:
        bmesh.ops.delete(bm_clean, geom=deg_faces, context="FACES")
    loose_verts = [v for v in bm_clean.verts if len(v.link_faces) == 0]
    if loose_verts:
        bmesh.ops.delete(bm_clean, geom=loose_verts, context="VERTS")
    bm_clean.to_mesh(char_obj.data)
    bm_clean.free()
    char_obj.data.update()

    # Extract vertex positions in numpy to normalize axes & facing
    pts = np.empty(len(char_obj.data.vertices) * 3, dtype=np.float64)
    char_obj.data.vertices.foreach_get("co", pts)
    pts = pts.reshape(-1, 3)

    # Rotate upright in numpy if tallest span is along Y or X (avoids Blender rotation_mode='QUATERNION' pitfalls)
    p_lo = np.percentile(pts, 0.5, axis=0)
    p_hi = np.percentile(pts, 99.5, axis=0)
    spans = p_hi - p_lo
    if spans[1] > spans[2] * 1.25 and spans[1] >= spans[0]:
        # +90 deg around X: (x, y, z) -> (x, -z, y)
        pts = np.stack([pts[:, 0], -pts[:, 2], pts[:, 1]], axis=1)
    elif spans[0] > spans[2] * 1.25 and spans[0] >= spans[1]:
        # -90 deg around Y: (x, y, z) -> (-z, y, x)
        pts = np.stack([-pts[:, 2], pts[:, 1], pts[:, 0]], axis=1)

    # Trim extreme vertical air-gap outlier spikes (<0.5% vertices isolated >4% below sole or above crown)
    z_col = pts[:, 2]
    z_raw_min, z_raw_max = float(z_col.min()), float(z_col.max())
    z_p05, z_p995 = float(np.percentile(z_col, 0.5)), float(np.percentile(z_col, 99.5))
    robust_h = max(1e-4, z_p995 - z_p05)
    outlier_indices = []
    if (z_p05 - z_raw_min) > 0.04 * robust_h:
        low_cut = z_p05 - 0.015 * robust_h
        if np.sum(z_col < low_cut) <= max(64, int(0.008 * len(z_col))):
            outlier_indices.extend(np.where(z_col < low_cut)[0].tolist())
    if (z_raw_max - z_p995) > 0.04 * robust_h:
        high_cut = z_p995 + 0.015 * robust_h
        if np.sum(z_col > high_cut) <= max(64, int(0.008 * len(z_col))):
            outlier_indices.extend(np.where(z_col > high_cut)[0].tolist())
    if outlier_indices:
        char_obj.data.vertices.foreach_set("co", pts.ravel())
        bm_trim = bmesh.new()
        bm_trim.from_mesh(char_obj.data)
        bm_trim.verts.ensure_lookup_table()
        del_v = [bm_trim.verts[idx] for idx in outlier_indices if idx < len(bm_trim.verts)]
        if del_v:
            bmesh.ops.delete(bm_trim, geom=del_v, context="VERTS")
            print(f"[BlenderRig] Trimmed {len(del_v)} floating spike outlier verts")
        bm_trim.to_mesh(char_obj.data)
        bm_trim.free()
        char_obj.data.update()
        pts = np.empty(len(char_obj.data.vertices) * 3, dtype=np.float64)
        char_obj.data.vertices.foreach_get("co", pts)
        pts = pts.reshape(-1, 3)

    # Center X/Y via torso median, shift floor Z=0, scale to target_height
    z_min, z_max = float(pts[:, 2].min()), float(pts[:, 2].max())
    raw_h = max(1e-4, z_max - z_min)
    scale = target_height / raw_h

    torso_mask = (pts[:, 2] >= z_min + 0.45 * raw_h) & (pts[:, 2] <= z_min + 0.80 * raw_h)
    cx = float(np.median(pts[torso_mask, 0])) if np.any(torso_mask) else float(np.median(pts[:, 0]))
    cy = float(np.median(pts[torso_mask, 1])) if np.any(torso_mask) else float(np.median(pts[:, 1]))

    pts[:, 0] = (pts[:, 0] - cx) * scale
    pts[:, 1] = (pts[:, 1] - cy) * scale
    pts[:, 2] = (pts[:, 2] - z_min) * scale

    # Auto-detect front direction in Blender (-Y = glTF +Z front) using foot-to-ankle extension
    yaw_deg = 0.0
    if front_yaw.lower() != "auto":
        yaw_deg = float(front_yaw)
    else:
        ankle_mask = (pts[:, 2] >= 0.07 * target_height) & (pts[:, 2] <= 0.14 * target_height)
        sole_mask = (pts[:, 2] >= 0.00 * target_height) & (pts[:, 2] <= 0.05 * target_height)
        if np.sum(ankle_mask) >= 12 and np.sum(sole_mask) >= 12:
            a_pts = pts[ankle_mask]
            s_pts = pts[sole_mask]
            # Look at max extension along +-X and +-Y relative to ankle center
            acx, acy = float(np.median(a_pts[:, 0])), float(np.median(a_pts[:, 1]))
            ext_ny = acy - float(np.percentile(s_pts[:, 1], 3))   # -Y front score
            ext_py = float(np.percentile(s_pts[:, 1], 97)) - acy  # +Y front score
            ext_px = float(np.percentile(s_pts[:, 0], 97)) - acx  # +X front score
            ext_nx = acx - float(np.percentile(s_pts[:, 0], 3))   # -X front score
            best_dir, best_val = max(
                [("-Y", ext_ny), ("+Y", ext_py), ("+X", ext_px), ("-X", ext_nx)],
                key=lambda kv: kv[1],
            )
            second_val = sorted([ext_ny, ext_py, ext_px, ext_nx], reverse=True)[1]
            # Rotate only when there's a clear non-negative foot-toe protrusion direction
            if best_val > second_val * 1.15:
                if best_dir == "+Y":
                    yaw_deg = 180.0
                elif best_dir == "+X":
                    yaw_deg = -90.0
                elif best_dir == "-X":
                    yaw_deg = 90.0
                print(f"[BlenderRig] Auto front orientation detected: {best_dir} -> yaw={yaw_deg} deg")

    if abs(yaw_deg) > 1e-3:
        ang = math.radians(yaw_deg)
        ca, sa = math.cos(ang), math.sin(ang)
        rx = ca * pts[:, 0] - sa * pts[:, 1]
        ry = sa * pts[:, 0] + ca * pts[:, 1]
        pts[:, 0], pts[:, 1] = rx, ry

    char_obj.data.vertices.foreach_set("co", pts.ravel())
    char_obj.data.update()

    # Light topological cleanup before optional decimation: strip tiny disconnected dust islands
    bm_iso = bmesh.new()
    bm_iso.from_mesh(char_obj.data)
    bm_iso.verts.ensure_lookup_table()
    bmesh.ops.remove_doubles(bm_iso, verts=bm_iso.verts, dist=1e-5)
    bm_iso.verts.ensure_lookup_table()
    if len(bm_iso.verts) > 500:
        seen_v = set()
        comps = []
        for v in bm_iso.verts:
            if v in seen_v:
                continue
            stack = [v]
            seen_v.add(v)
            comp = []
            while stack:
                cur = stack.pop()
                comp.append(cur)
                for e in cur.link_edges:
                    ov = e.other_vert(cur)
                    if ov not in seen_v:
                        seen_v.add(ov)
                        stack.append(ov)
            comps.append(comp)
        if len(comps) > 1:
            max_comp = max(len(c) for c in comps)
            if max_comp >= 500:
                dust_verts = [v for c in comps if len(c) < 16 for v in c]
                if dust_verts and len(dust_verts) < int(0.08 * len(bm_iso.verts)):
                    bmesh.ops.delete(bm_iso, geom=dust_verts, context="VERTS")
                    print(f"[BlenderRig] Stripped {len(dust_verts)} floating dust vertices")
    bm_iso.to_mesh(char_obj.data)
    bm_iso.free()
    char_obj.data.update()

    # Detail-preserving decimation: lock head/face/hands geometry at 100% density via invert_vertex_group
    n_polys = len(char_obj.data.polygons)
    if max_faces > 0 and n_polys > max_faces:
        ratio = float(max_faces) / float(n_polys)
        v_pts = np.empty(len(char_obj.data.vertices) * 3, dtype=np.float64)
        char_obj.data.vertices.foreach_get("co", v_pts)
        v_pts = v_pts.reshape(-1, 3)
        head_mask = v_pts[:, 2] >= 0.79 * target_height
        hand_mask = (v_pts[:, 2] >= 0.39 * target_height) & (v_pts[:, 2] <= 0.72 * target_height) & (np.abs(v_pts[:, 0]) >= 0.14 * target_height)
        low_hand = (v_pts[:, 2] >= 0.42 * target_height) & (v_pts[:, 2] <= 0.55 * target_height) & (np.abs(v_pts[:, 0]) >= 0.095 * target_height)
        preserve_idx = np.where(head_mask | hand_mask | low_hand)[0].tolist()
        vg_preserve = None
        if 16 <= len(preserve_idx) < int(0.68 * len(v_pts)):
            vg_preserve = char_obj.vertex_groups.get("SurrealPreserveDetail") or char_obj.vertex_groups.new(name="SurrealPreserveDetail")
            vg_preserve.add(preserve_idx, 1.0, "REPLACE")
        print(f"[BlenderRig] Decimating mesh {n_polys} polys -> target ~{max_faces} (ratio={ratio:.3f}, protected={len(preserve_idx)} face/hand verts)")
        mod = char_obj.modifiers.new(name="StudioDecimate", type="DECIMATE")
        mod.decimate_type = "COLLAPSE"
        mod.ratio = max(0.05, min(1.0, ratio))
        if vg_preserve is not None:
            mod.vertex_group = vg_preserve.name
            mod.vertex_group_factor = 10.0
            mod.invert_vertex_group = True
        mod.use_collapse_triangulate = True
        bpy.ops.object.modifier_apply(modifier=mod.name)
        if vg_preserve is not None and vg_preserve.name in char_obj.vertex_groups:
            char_obj.vertex_groups.remove(char_obj.vertex_groups[vg_preserve.name])

    # Light manifold weld & outward normal recomputation (helps ARMATURE_AUTO heat solver)
    bm = bmesh.new()
    bm.from_mesh(char_obj.data)
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=0.00025)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.faces.ensure_lookup_table()
    # Flip any disconnected open fragment whose faces mostly point radially inward toward Z spine
    inw_faces = []
    seen_f = set()
    for f in bm.faces:
        if f in seen_f:
            continue
        stack = [f]
        seen_f.add(f)
        comp_f = []
        while stack:
            cur = stack.pop()
            comp_f.append(cur)
            for e in cur.edges:
                for lf in e.link_faces:
                    if lf not in seen_f:
                        seen_f.add(lf)
                        stack.append(lf)
        if len(comp_f) <= 64:
            rad_score = 0.0
            for cf in comp_f:
                cc = cf.calc_center_median()
                rad_score += cf.normal.x * cc.x + cf.normal.y * cc.y
            if rad_score < -1e-4:
                inw_faces.extend(comp_f)
    if inw_faces:
        bmesh.ops.reverse_faces(bm, faces=inw_faces)
    bm.to_mesh(char_obj.data)
    bm.free()
    char_obj.data.update()

    # Ensure every polygon uses smooth shading & matte-organic PBR roughness for non-metallic skin/cloth
    for p in char_obj.data.polygons:
        p.use_smooth = True
    for mat in char_obj.data.materials:
        if mat and mat.use_nodes and mat.node_tree:
            mat.blend_method = "OPAQUE"
            for node in mat.node_tree.nodes:
                if node.type == "BSDF_PRINCIPLED":
                    m_inp = node.inputs.get("Metallic")
                    r_inp = node.inputs.get("Roughness")
                    if m_inp and not m_inp.is_linked and m_inp.default_value < 0.45:
                        m_inp.default_value = 0.0
                        if r_inp and not r_inp.is_linked:
                            r_inp.default_value = max(float(r_inp.default_value), 0.78)

    print(f"[BlenderRig] Prepared StudioCharacter: {len(char_obj.data.vertices)} verts, {len(char_obj.data.polygons)} polys, height={target_height:.2f}m")
    return char_obj


def slice_centroid(pts: np.ndarray, z_lo: float, z_hi: float, x_lo=-10.0, x_hi=10.0):
    m = (pts[:, 2] >= z_lo) & (pts[:, 2] <= z_hi) & (pts[:, 0] >= x_lo) & (pts[:, 0] <= x_hi)
    if np.sum(m) < 4:
        return None
    sub = pts[m]
    return np.array([float(np.median(sub[:, 0])), float(np.median(sub[:, 1])), float(np.median(sub[:, 2]))])


def trace_arm_chain(pts: np.ndarray, side_sign: float, H: float, shoulder_pivot: np.ndarray, torso_edge_x: float):
    """
    Detects shoulder -> elbow -> wrist -> hand tip along left (+1) or right (-1) arm
    across T-pose, A-pose, or tucked/crossed downward arms while staying strictly inside mesh bounds.
    """
    x_thresh = max(torso_edge_x * 1.12, 0.135 * H)
    if side_sign > 0:
        x_mask = pts[:, 0] > x_thresh
    else:
        x_mask = pts[:, 0] < -x_thresh

    arm_mask = x_mask & (pts[:, 2] >= 0.42 * H) & (pts[:, 2] <= 0.88 * H)
    arm_pts = pts[arm_mask]

    def tucked_contour_arm():
        def lat_pt(z_rel: float, x_frac: float):
            sl = pts[(pts[:, 2] >= (z_rel - 0.035) * H) & (pts[:, 2] <= (z_rel + 0.035) * H)]
            side_sl = sl[(sl[:, 0] > 0.03 * H)] if side_sign > 0 else sl[(sl[:, 0] < -0.03 * H)]
            if len(side_sl) >= 6:
                lat_x = float(np.percentile(side_sl[:, 0], 85 if side_sign > 0 else 15))
                return np.array([lat_x * x_frac, float(np.median(side_sl[:, 1])), z_rel * H])
            return np.array([side_sign * 0.095 * H, shoulder_pivot[1], z_rel * H])

        s_root = lat_pt(0.78, 0.78)
        s_elb = lat_pt(0.64, 0.82)
        s_wri = lat_pt(0.51, 0.80)
        s_tip = lat_pt(0.45, 0.78)
        return s_root, s_elb, s_wri, s_tip, False

    if len(arm_pts) < 28:
        return tucked_contour_arm()

    arm_z_span = float(np.percentile(arm_pts[:, 2], 98) - np.percentile(arm_pts[:, 2], 2))
    dists = np.linalg.norm(arm_pts - shoulder_pivot, axis=1)
    max_reach = float(np.percentile(dists, 98))
    if max_reach < 0.16 * H or arm_z_span < 0.14 * H:
        return tucked_contour_arm()

    far_idx = int(np.argmax(dists))
    far_pt = arm_pts[far_idx].copy()

    def band_med(r0, r1, frac):
        bm = (dists >= r0 * max_reach) & (dists <= r1 * max_reach)
        if np.sum(bm) < 5:
            return (1.0 - frac) * shoulder_pivot + frac * far_pt
        sub = arm_pts[bm]
        return np.array([float(np.median(sub[:, 0])), float(np.median(sub[:, 1])), float(np.median(sub[:, 2]))])

    arm_root = band_med(0.02, 0.18, 0.10)
    if side_sign * arm_root[0] < 0.075 * H:
        arm_root[0] = side_sign * 0.088 * H
    arm_root[2] = 0.78 * shoulder_pivot[2] + 0.22 * arm_root[2]

    elbow = band_med(0.38, 0.56, 0.48)
    wrist = band_med(0.72, 0.88, 0.82)
    tip = band_med(0.90, 1.00, 0.96)
    if np.linalg.norm(tip - wrist) < 0.025 * H:
        u = wrist - elbow
        n = float(np.linalg.norm(u))
        tip = wrist + (u / max(1e-5, n)) * min(0.055 * H, 0.22 * max_reach)

    # Require wide A/T-pose reach or a genuine armpit air-gap valley before marking arm free
    has_wide_reach = abs(wrist[0]) > 0.185 * H and abs(elbow[0]) > 0.155 * H
    armpit_air_gap = False
    sl_gap = pts[(pts[:, 2] >= 0.58 * H) & (pts[:, 2] <= 0.72 * H)]
    side_sl = sl_gap[sl_gap[:, 0] > 0] if side_sign > 0 else sl_gap[sl_gap[:, 0] < 0]
    if len(side_sl) >= 20:
        axs = np.abs(side_sl[:, 0])
        outer = min(0.24 * H, max(abs(wrist[0]), abs(elbow[0])))
        if outer > 0.125 * H:
            gh, _ = np.histogram(axs[axs <= outer], bins=10)
            inner_peak = int(np.max(gh[1:5]))
            valley = int(np.min(gh[3:8]))
            arm_peak = int(np.max(gh[6:]))
            if inner_peak >= 8 and valley <= max(2, int(0.12 * inner_peak)) and arm_peak >= max(5, int(0.15 * inner_peak)):
                armpit_air_gap = True

    if not (has_wide_reach or armpit_air_gap):
        return tucked_contour_arm()

    return arm_root, elbow, wrist, tip, True


def detect_humanoid_joints(char_obj, H: float):
    pts = np.empty(len(char_obj.data.vertices) * 3, dtype=np.float64)
    char_obj.data.vertices.foreach_get("co", pts)
    pts = pts.reshape(-1, 3)

    def core_pt(z_rel, y_bias=0.0):
        c = slice_centroid(pts, (z_rel - 0.03) * H, (z_rel + 0.03) * H, -0.11 * H, 0.11 * H)
        if c is None:
            return np.array([0.0, y_bias, z_rel * H])
        return np.array([c[0] * 0.35, c[1] + y_bias, z_rel * H])

    hips = core_pt(0.51)
    spine = core_pt(0.58)
    spine1 = core_pt(0.65)
    spine2 = core_pt(0.73)
    neck = core_pt(0.815)
    head = core_pt(0.865)
    head_top = np.array([head[0], head[1], 0.985 * H])

    # Estimate torso vs arm separation X edge from upper chest (z in 0.60..0.73H)
    chest_slice = pts[(pts[:, 2] >= 0.60 * H) & (pts[:, 2] <= 0.72 * H)]
    torso_edge = 0.098 * H
    if len(chest_slice) > 40:
        abs_x = np.abs(chest_slice[:, 0])
        hist, edges = np.histogram(abs_x[(abs_x >= 0.05 * H) & (abs_x <= 0.19 * H)], bins=14)
        if len(hist) >= 6:
            # Lowest density notch around armpit gap separates hanging arms from ribcage
            notch_idx = int(np.argmin(hist[2:-2])) + 2
            if hist[notch_idx] <= np.max(hist) * 0.45:
                torso_edge = float(0.5 * (edges[notch_idx] + edges[notch_idx + 1]))

    sh_l_pivot = np.array([torso_edge * 0.92, spine2[1], 0.79 * H])
    sh_r_pivot = np.array([-torso_edge * 0.92, spine2[1], 0.79 * H])

    l_arm, l_el, l_wr, l_tip, l_free = trace_arm_chain(pts, +1.0, H, sh_l_pivot, torso_edge)
    r_arm, r_el, r_wr, r_tip, r_free = trace_arm_chain(pts, -1.0, H, sh_r_pivot, torso_edge)
    char_obj["surreal_left_arm_free"] = bool(l_free)
    char_obj["surreal_right_arm_free"] = bool(r_free)
    if not l_free or not r_free:
        print(f"[BlenderRig] Tucked/fused arm mode: left_free={l_free}, right_free={r_free} (dampens bat-wing shoulder swing)")

    l_sh = np.array([0.045 * H, spine2[1] * 0.7 + l_arm[1] * 0.3, 0.79 * H])
    r_sh = np.array([-0.045 * H, spine2[1] * 0.7 + r_arm[1] * 0.3, 0.79 * H])

    # Leg joints from left (+X) & right (-X) halves
    def leg_side(sign: float):
        x0, x1 = (0.012 * H, 0.26 * H) if sign > 0 else (-0.26 * H, -0.012 * H)
        knee = slice_centroid(pts, 0.25 * H, 0.31 * H, x0, x1)
        ankle = slice_centroid(pts, 0.04 * H, 0.09 * H, x0, x1)
        thigh = slice_centroid(pts, 0.39 * H, 0.46 * H, x0, x1)
        if ankle is None:
            ankle = np.array([sign * 0.075 * H, 0.01 * H, 0.055 * H])
        if knee is None:
            knee = np.array([sign * 0.08 * H, -0.005 * H, 0.28 * H])
        if thigh is None:
            up_x = float(np.clip(0.82 * abs(knee[0]), 0.055 * H, 0.11 * H)) * sign
            up_y = hips[1]
        else:
            up_x = float(np.clip(abs(thigh[0]) * 0.90, 0.055 * H, 0.11 * H)) * sign
            up_y = float(0.6 * hips[1] + 0.4 * thigh[1])

        up_leg = np.array([up_x, up_y, 0.48 * H])
        knee = np.array([float(np.clip(abs(knee[0]), 0.045 * H, 0.16 * H)) * sign, knee[1], 0.28 * H])
        ankle = np.array([float(np.clip(abs(ankle[0]), 0.04 * H, 0.18 * H)) * sign, ankle[1], 0.055 * H])

        # Toe direction along -Y front
        foot_pts = pts[(pts[:, 2] <= 0.05 * H) & (pts[:, 0] >= x0) & (pts[:, 0] <= x1)]
        if len(foot_pts) >= 5:
            toe_y = float(np.percentile(foot_pts[:, 1], 20))
            toe_end_y = float(np.percentile(foot_pts[:, 1], 4))
            toe_y = min(toe_y, ankle[1] - 0.05 * H)
            toe_end_y = min(toe_end_y, toe_y - 0.03 * H)
        else:
            toe_y = ankle[1] - 0.075 * H
            toe_end_y = ankle[1] - 0.125 * H

        toe_base = np.array([ankle[0], toe_y, 0.014 * H])
        toe_end = np.array([ankle[0], toe_end_y, 0.012 * H])
        return up_leg, knee, ankle, toe_base, toe_end

    l_ul, l_kn, l_ft, l_tb, l_te = leg_side(+1.0)
    r_ul, r_kn, r_ft, r_tb, r_te = leg_side(-1.0)

    joints = {
        "Hips": hips,
        "Spine": spine,
        "Spine1": spine1,
        "Spine2": spine2,
        "Neck": neck,
        "Head": head,
        "HeadTop": head_top,
        "LeftShoulder": l_sh,
        "LeftArm": l_arm,
        "LeftForeArm": l_el,
        "LeftHand": l_wr,
        "LeftHandTip": l_tip,
        "RightShoulder": r_sh,
        "RightArm": r_arm,
        "RightForeArm": r_el,
        "RightHand": r_wr,
        "RightHandTip": r_tip,
        "LeftUpLeg": l_ul,
        "LeftLeg": l_kn,
        "LeftFoot": l_ft,
        "LeftToeBase": l_tb,
        "LeftToeEnd": l_te,
        "RightUpLeg": r_ul,
        "RightLeg": r_kn,
        "RightFoot": r_ft,
        "RightToeBase": r_tb,
        "RightToeEnd": r_te,
    }

    # Safety clamp: keep limb joints tightly anchored inside/near actual mesh vertices
    # so disconnected arms never stick far out in empty air and pull mesh spikes.
    for jname in ("LeftArm", "LeftForeArm", "LeftHand", "LeftHandTip",
                  "RightArm", "RightForeArm", "RightHand", "RightHandTip",
                  "LeftLeg", "RightLeg"):
        jp = joints[jname]
        d2 = np.sum((pts - jp) ** 2, axis=1)
        min_idx = int(np.argmin(d2))
        min_d = math.sqrt(float(d2[min_idx]))
        if min_d > 0.025 * H:
            nearest = pts[min_idx].copy()
            # Pull slightly inward toward torso spine centerline
            nearest[0] *= 0.88
            joints[jname] = nearest

    return joints


def build_humanoid_armature(joints: dict, name="AvatarRig"):
    arm_data = bpy.data.armatures.new(name + "Data")
    arm_obj = bpy.data.objects.new(name, arm_data)
    bpy.context.collection.objects.link(arm_obj)
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.mode_set(mode="EDIT")

    edit_bones = {}
    for bname in CORE_BONES:
        if bname not in BONE_SEGMENT_CHILD:
            continue
        child_name = BONE_SEGMENT_CHILD[bname]
        h = mathutils.Vector(joints[bname].tolist())
        t = mathutils.Vector(joints[child_name].tolist())
        if (t - h).length < 0.015:
            t = h + mathutils.Vector((0.0, 0.0, 0.05))
        eb = arm_data.edit_bones.new(bname)
        eb.head = h
        eb.tail = t
        eb.use_deform = True
        eb.use_connect = False
        # Align roll cleanly toward world front (-Y) or +Z for arms so twist stays consistent
        if "Arm" in bname or "Shoulder" in bname or "Hand" in bname:
            eb.align_roll(mathutils.Vector((0.0, -1.0, 0.0)))
        else:
            eb.align_roll(mathutils.Vector((0.0, -1.0, 0.0)))
        edit_bones[bname] = eb

    for bname, eb in edit_bones.items():
        pname = BONE_PARENTS.get(bname)
        if pname and pname in edit_bones:
            eb.parent = edit_bones[pname]

    bpy.ops.object.mode_set(mode="OBJECT")
    return arm_obj


def compute_capsule_distances(verts: np.ndarray, seg_a: np.ndarray, seg_b: np.ndarray):
    """Returns [N_verts, N_bones] Euclidean distances to each bone segment."""
    ab = seg_b - seg_a  # [B, 3]
    ab_len2 = np.sum(ab * ab, axis=1, keepdims=True).T + 1e-12  # [1, B]
    ap = verts[:, None, :] - seg_a[None, :, :]  # [N, B, 3]
    t = np.sum(ap * ab[None, :, :], axis=2) / ab_len2  # [N, B]
    t = np.clip(t, 0.0, 1.0)
    proj = seg_a[None, :, :] + t[:, :, None] * ab[None, :, :]
    return np.linalg.norm(verts[:, None, :] - proj, axis=2)


def bind_smooth_skin_weights(char_obj, arm_obj, H: float = 1.68):
    mesh = char_obj.data
    n_verts = len(mesh.vertices)

    # First ensure vertex groups exist in arm bone order
    for b in arm_obj.data.bones:
        if b.name not in char_obj.vertex_groups:
            char_obj.vertex_groups.new(name=b.name)

    # Attempt Blender's native volumetric Bone Heat solver (ARMATURE_AUTO)
    auto_ok = False
    try:
        bpy.ops.object.select_all(action="DESELECT")
        char_obj.select_set(True)
        arm_obj.select_set(True)
        bpy.context.view_layer.objects.active = arm_obj
        bpy.ops.object.parent_set(type="ARMATURE_AUTO")
        auto_ok = True
    except Exception as exc:
        print(f"[BlenderRig] ARMATURE_AUTO exception -> fallback solver: {exc}")
        bpy.ops.object.select_all(action="DESELECT")
        char_obj.select_set(True)
        arm_obj.select_set(True)
        bpy.context.view_layer.objects.active = arm_obj
        bpy.ops.object.parent_set(type="ARMATURE")

    # Build sparse vertex-to-bone weight matrix from ARMATURE_AUTO result
    vg_names = [vg.name for vg in char_obj.vertex_groups]
    vg_name_to_col = {name: i for i, name in enumerate(vg_names)}
    n_bones = len(vg_names)
    weights = np.zeros((n_verts, n_bones), dtype=np.float32)

    for vi, v in enumerate(mesh.vertices):
        for g in v.groups:
            if 0 <= g.group < n_bones:
                weights[vi, g.group] = g.weight

    row_sums = weights.sum(axis=1)
    unweighted_mask = row_sums < 0.01
    n_unweighted = int(np.sum(unweighted_mask))
    print(f"[BlenderRig] ARMATURE_AUTO ok={auto_ok}: weighted={n_verts - n_unweighted}/{n_verts}, unweighted={n_unweighted}")

    # Build mesh edge adjacency list once (for topological weight propagation + Laplacian smoothing)
    edge_u = np.array([e.vertices[0] for e in mesh.edges], dtype=np.int32)
    edge_v = np.array([e.vertices[1] for e in mesh.edges], dtype=np.int32)

    if n_unweighted > 0 and n_unweighted < n_verts:
        # First propagate heat weights topologically to pockets connected to the main body
        for _ in range(18):
            still_bad = weights.sum(axis=1) < 0.01
            if not np.any(still_bad):
                break
            accum = np.zeros_like(weights)
            w_good = (weights.sum(axis=1) >= 0.01).astype(np.float32)
            np.add.at(accum, edge_u, weights[edge_v] * w_good[edge_v, None])
            np.add.at(accum, edge_v, weights[edge_u] * w_good[edge_u, None])
            asum = accum.sum(axis=1)
            fill = still_bad & (asum > 1e-5)
            if not np.any(fill):
                break
            weights[fill] = accum[fill] / asum[fill, None]

    # Capsule-distance fallback ONLY for vertices still unweighted (disconnected props or failed heat solver)
    still_bad = weights.sum(axis=1) < 0.01
    n_still = int(np.sum(still_bad))
    if n_still > 0:
        print(f"[BlenderRig] Filling {n_still} remaining vertices via anatomical capsule solver...")
        pts = np.empty(n_verts * 3, dtype=np.float32)
        mesh.vertices.foreach_get("co", pts)
        pts = pts.reshape(-1, 3)

        seg_a = np.zeros((n_bones, 3), dtype=np.float32)
        seg_b = np.zeros((n_bones, 3), dtype=np.float32)
        arm_x = 0.105 * 1.68
        for bname, col in vg_name_to_col.items():
            bone = arm_obj.data.bones[bname]
            seg_a[col] = np.array(bone.head_local, dtype=np.float32)
            seg_b[col] = np.array(bone.tail_local, dtype=np.float32)
            if bname == "LeftArm":
                arm_x = float(bone.head_local.x)

        bad_pts = pts[still_bad]
        dists = compute_capsule_distances(bad_pts, seg_a, seg_b)

        # Prevent left/right cross-leg or arm-to-hip bleed in capsule fallback
        h_scale = H / 1.68
        for bname, col in vg_name_to_col.items():
            if bname.startswith("Left"):
                dists[bad_pts[:, 0] < -0.02 * h_scale, col] += 0.45 * h_scale
            elif bname.startswith("Right"):
                dists[bad_pts[:, 0] > 0.02 * h_scale, col] += 0.45 * h_scale
            if "Arm" in bname or "Hand" in bname:
                # Discourage arms stealing low skirt/hip vertices inside core radius
                dists[(np.abs(bad_pts[:, 0]) < arm_x * 0.85) & (bad_pts[:, 2] < 0.685 * H), col] += 0.35 * h_scale

        # Inverse-distance-4th-power soft weights around closest bone capsule
        d_min = np.min(dists, axis=1, keepdims=True)
        rel = dists - d_min
        raw_w = np.exp(-np.square(rel / max(0.02, 0.055 * h_scale)))
        raw_w /= np.maximum(1e-8, raw_w.sum(axis=1, keepdims=True))
        weights[still_bad] = raw_w

    # 3 gentle topological Laplacian weight smoothing passes + strict top-4 normalization (glTF limit)
    if len(edge_u) > 0:
        deg = np.zeros(n_verts, dtype=np.float32)
        np.add.at(deg, edge_u, 1.0)
        np.add.at(deg, edge_v, 1.0)
        deg = np.maximum(1.0, deg)[:, None]
        for _ in range(3):
            nbr = np.zeros_like(weights)
            np.add.at(nbr, edge_u, weights[edge_v])
            np.add.at(nbr, edge_v, weights[edge_u])
            weights = 0.65 * weights + 0.35 * (nbr / deg)

    # Keep only top 4 influences per vertex and re-normalize to 1.0
    if n_bones > 4:
        top4 = np.argpartition(weights, -4, axis=1)[:, -4:]
        masked = np.zeros_like(weights)
        rows = np.arange(n_verts)[:, None]
        masked[rows, top4] = weights[rows, top4]
        weights = masked
    row_sums = np.maximum(1e-8, weights.sum(axis=1, keepdims=True))
    weights = weights / row_sums

    # Write final clean weights back into Blender vertex groups
    for vg in char_obj.vertex_groups:
        vg.remove(list(range(n_verts)))
    for col, vg in enumerate(char_obj.vertex_groups):
        nz = np.where(weights[:, col] > 0.002)[0]
        for vi in nz:
            vg.add([int(vi)], float(weights[vi, col]), "REPLACE")


def retarget_mixamo_dance(arm_obj, ref_glb_path: str, step: int = 2, clip_name: str = "StudioDance", limb_flags: dict = None):
    if not ref_glb_path or not os.path.exists(ref_glb_path):
        print("[BlenderRig] No --ref-anim found; exporting idle rigged pose.")
        return

    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=ref_glb_path)
    src_objs = [o for o in bpy.data.objects if o not in before]
    src_arms = [o for o in src_objs if o.type == "ARMATURE"]
    if not src_arms:
        for o in src_objs:
            bpy.data.objects.remove(o, do_unlink=True)
        print("[BlenderRig] Reference animation GLB had no armature.")
        return

    src_arm = src_arms[0]
    src_act = src_arm.animation_data.action if (src_arm.animation_data and src_arm.animation_data.action) else None
    if not src_act:
        for o in src_objs:
            bpy.data.objects.remove(o, do_unlink=True)
        print("[BlenderRig] Reference armature had no animation action.")
        return

    # Map canonical names ("Hips", "LeftArm", ...) -> source bone name
    src_map = {}
    for b in src_arm.data.bones:
        cn = canonical_mixamo_name(b.name)
        if cn in CORE_BONES and cn not in src_map:
            src_map[cn] = b.name

    # World rest transform & true anatomical rest vector per bone on BOTH rigs
    src_mw3 = src_arm.matrix_world.to_3x3().normalized()
    tgt_mw3 = arm_obj.matrix_world.to_3x3().normalized()

    src_rest_world_rot = {}
    src_rest_dir = {}
    src_hips_rest_pos = mathutils.Vector((0.0, 0.0, 1.0))

    for cn, sname in src_map.items():
        sb = src_arm.data.bones[sname]
        src_rest_world_rot[cn] = (src_mw3 @ sb.matrix_local.to_3x3()).normalized()
        sh = src_arm.matrix_world @ sb.head_local
        if cn == "Hips":
            src_hips_rest_pos = sh.copy()
        child_cn = BONE_SEGMENT_CHILD.get(cn)
        if child_cn and child_cn in src_map:
            sc = src_arm.matrix_world @ src_arm.data.bones[src_map[child_cn]].head_local
            vec = sc - sh
            if vec.length > 1e-4:
                src_rest_dir[cn] = vec.normalized()

    tgt_rest_world_rot = {}
    tgt_rest_dir = {}
    tgt_hips_rest_pos = mathutils.Vector((0.0, 0.0, 0.85))
    q_rest_align = {}

    for cn in DEFORM_BONES:
        if cn not in arm_obj.data.bones:
            continue
        tb = arm_obj.data.bones[cn]
        tgt_rest_world_rot[cn] = (tgt_mw3 @ tb.matrix_local.to_3x3()).normalized()
        th = arm_obj.matrix_world @ tb.head_local
        tt = arm_obj.matrix_world @ tb.tail_local
        if cn == "Hips":
            tgt_hips_rest_pos = th.copy()
        if (tt - th).length > 1e-4:
            tgt_rest_dir[cn] = (tt - th).normalized()
        if cn in src_rest_dir and cn in tgt_rest_dir:
            q_rest_align[cn] = tgt_rest_dir[cn].rotation_difference(src_rest_dir[cn])
        else:
            q_rest_align[cn] = mathutils.Quaternion((1.0, 0.0, 0.0, 0.0))

    hips_height_ratio = float(tgt_hips_rest_pos.z) / max(0.05, float(src_hips_rest_pos.z))

    # Prepare target action
    scene = bpy.context.scene
    f_start = int(round(src_act.frame_range[0]))
    f_end = int(round(src_act.frame_range[1]))
    if f_end <= f_start:
        f_end = f_start + 30
    scene.frame_start = f_start
    scene.frame_end = f_end

    if not arm_obj.animation_data:
        arm_obj.animation_data_create()
    tgt_act = bpy.data.actions.new(name=clip_name)
    arm_obj.animation_data.action = tgt_act

    for pb in arm_obj.pose.bones:
        pb.rotation_mode = "QUATERNION"

    # Precompute target armature local rest transform chain for exact top-down pose conversion
    arm_inv_mw = arm_obj.matrix_world.inverted()
    frames = list(range(f_start, f_end + 1, max(1, step)))
    if frames[-1] != f_end:
        frames.append(f_end)

    for f in frames:
        scene.frame_set(f)
        bpy.context.view_layer.update()

        posed_arm_mats = {}
        for cn in DEFORM_BONES:
            if cn not in arm_obj.pose.bones or cn not in src_map:
                continue
            spb = src_arm.pose.bones[src_map[cn]]
            tpb = arm_obj.pose.bones[cn]
            tb = tpb.bone

            src_pose_w3 = (src_mw3 @ spb.matrix.to_3x3()).normalized()
            q_delta = (src_pose_w3 @ src_rest_world_rot[cn].inverted()).to_quaternion()
            q_align = q_rest_align[cn]

            if limb_flags:
                is_l = cn in ("LeftShoulder", "LeftArm", "LeftForeArm", "LeftHand")
                is_r = cn in ("RightShoulder", "RightArm", "RightForeArm", "RightHand")
                if (is_l and not limb_flags.get("left", True)) or (is_r and not limb_flags.get("right", True)):
                    q_ident = mathutils.Quaternion((1.0, 0.0, 0.0, 0.0))
                    q_delta = q_ident.slerp(q_delta, 0.14)
                    q_align = q_ident.slerp(q_align, 0.18)

            desired_w3 = (q_delta @ q_align).to_matrix() @ tgt_rest_world_rot[cn]
            desired_arm3 = arm_inv_mw.to_3x3().normalized() @ desired_w3

            # Determine posed head in armature space
            if cn == "Hips":
                src_hips_pose = src_arm.matrix_world @ spb.head
                delta_w = (src_hips_pose - src_hips_rest_pos) * hips_height_ratio
                # Clamp extreme downward squat dips so Studio idols stay upright beside group models
                delta_w.z = max(-0.055 * float(tgt_hips_rest_pos.z), float(delta_w.z))
                head_arm = tb.head_local + (arm_inv_mw.to_3x3() @ delta_w)
                mat_arm = desired_arm3.to_4x4()
                mat_arm.translation = head_arm
                # Convert relative to bone rest local space (root has no parent)
                rel = tb.matrix_local.inverted() @ mat_arm
                tpb.location = rel.to_translation()
                tpb.rotation_quaternion = rel.to_quaternion()
                tpb.keyframe_insert(data_path="location", frame=f)
                tpb.keyframe_insert(data_path="rotation_quaternion", frame=f)
                posed_arm_mats[cn] = mat_arm
            else:
                pname = BONE_PARENTS.get(cn)
                if pname and pname in posed_arm_mats:
                    parent_posed_arm = posed_arm_mats[pname]
                    pb_parent_bone = arm_obj.data.bones[pname]
                    rest_rel = pb_parent_bone.matrix_local.inverted() @ tb.matrix_local
                    pred_arm = parent_posed_arm @ rest_rel
                else:
                    pred_arm = tb.matrix_local.copy()

                mat_arm = desired_arm3.to_4x4()
                mat_arm.translation = pred_arm.translation
                local_delta = pred_arm.inverted() @ mat_arm
                tpb.rotation_quaternion = local_delta.to_quaternion()
                tpb.keyframe_insert(data_path="rotation_quaternion", frame=f)
                posed_arm_mats[cn] = mat_arm

    # Remove temporary reference rig, custom bone shapes, actions, and stray objects cleanly before GLB export
    for pb in arm_obj.pose.bones:
        pb.custom_shape = None
    for o in list(bpy.data.objects):
        if o in src_objs or o != arm_obj and o.name != "AvatarMesh":
            bpy.data.objects.remove(o, do_unlink=True)
    for act in list(bpy.data.actions):
        if act != tgt_act:
            bpy.data.actions.remove(act, do_unlink=True)
    bpy.context.view_layer.objects.active = arm_obj
    scene.frame_set(f_start)
    print(f"[BlenderRig] Retargeted '{clip_name}' ({len(frames)} keyframes, frames {f_start}..{f_end})")


def export_rigged_glb(char_obj, arm_obj, output_glb: str):
    import tempfile
    out_dir = os.path.dirname(os.path.abspath(output_glb))
    os.makedirs(out_dir, exist_ok=True)
    for o in list(bpy.data.objects):
        if o != char_obj and o != arm_obj:
            bpy.data.objects.remove(o, do_unlink=True)
    for pb in arm_obj.pose.bones:
        pb.custom_shape = None

    # Convert WEBP or exotic packed images to standard PNG so glTF 2.0 exports universal image/png
    # (avoids EXT_texture_webp extensions unsupported by lightweight glTF viewers/engines).
    with tempfile.TemporaryDirectory(prefix="surreal_pngtex_") as png_tmp:
        for idx, img in enumerate(bpy.data.images):
            if img.size[0] <= 0 or img.size[1] <= 0:
                continue
            fmt = (img.file_format or "").upper()
            if fmt not in ("PNG", "JPEG") or not img.packed_file:
                png_path = os.path.join(png_tmp, f"tex_{idx}.png")
                img.filepath_raw = png_path
                img.file_format = "PNG"
                img.save()
                img.filepath = png_path
                img.reload()
                img.file_format = "PNG"
                img.pack()

        bpy.ops.object.select_all(action="DESELECT")
        arm_obj.select_set(True)
        char_obj.select_set(True)
        bpy.context.view_layer.objects.active = arm_obj

        bpy.ops.export_scene.gltf(
            filepath=output_glb,
            export_format="GLB",
            use_selection=True,
            export_yup=True,
            export_texcoords=True,
            export_normals=True,
            export_colors=True,
            export_materials="EXPORT",
            export_image_format="AUTO",
            export_skins=True,
            export_def_bones=True,
            export_influence_nb=4,
            export_animations=True,
            export_frame_range=True,
            export_frame_step=1,
            export_force_sampling=True,
            export_bake_animation=True,
            export_anim_slide_to_zero=True,
            export_apply=False,
        )
    print(f"[BlenderRig] Exported rigged GLB -> {output_glb} ({os.path.getsize(output_glb)} bytes)")


