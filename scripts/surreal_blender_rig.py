#!/usr/bin/env python3
"""
AION SURREAL 3D ENGINE - LOCAL ZERO-VRAM BLENDER 4.0+ HUMANOID AUTO-RIGGER
=============================================================================
Takes ANY static 3D character mesh (.glb / .gltf / .obj) generated by Studio
AI models (Hunyuan3D, TRELLIS, InstantMesh, Tripo3D, Meshy, etc.) and:
  1. Normalizes scale (1.68 m height), grounds soles at Z=0, centers torso.
  2. Auto-detects front facing (-Y in Blender = +Z in glTF) via foot geometry.
  3. Preserves high-res embedded PBR textures, UVs, and vertex colors (COLOR_0),
     optionally decimating extreme Marching-Cubes densities (>48k faces) cleanly.
  4. Detects anatomical joints directly inside the mesh's 3D silhouette
     (supporting T-pose, A-pose, and casual standing arms/legs).
  5. Builds a clean 22-bone Mixamo-compatible humanoid skeleton.
  6. Binds smooth skin weights (Blender Bone Heat ARMATURE_AUTO + BFS/capsule
     geodesic weight solver + Laplacian smoothing for 0 unweighted vertices).
  7. Retargets Mixamo dance animations cleanly onto the fitted rest pose and
     exports an animated, rigged .glb ready for SurrealSkeletalLoader.

Usage:
  blender --background --python surreal_blender_rig.py -- \
    <input_mesh.glb|obj> <output_rigged.glb> \
    [--ref-anim assets/models/dancing_stormtrooper.glb] \
    [--height 1.68] [--front-yaw auto|0|90|180|270] [--max-faces 100000]
"""

